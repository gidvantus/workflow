/**
 * Числа и даты для экрана одним местом: стоимость задачи, сумма строки журнала, итог
 * проекта, цены за токены, количества токенов и дата записи.
 *
 * Фронт деньги не считает: сервер отдаёт суммы строкой с фиксированным числом знаков
 * (`"1250.00"`), а цена — с шестью (`"0.270000"`). Здесь строка только переставляется
 * в русский вид: пробел между тысячами, запятая перед копейками. Округления и перевода
 * копеек в рубли нет.
 *
 * Два вида денег, потому что их два в продукте:
 *
 * - `formatMoney` — рубли задачи (`tasks.cost`), ровно два знака. Эта половина #72 не
 *   касается: сервер печатает её прежним `format_money`, и знак `₽` остаётся;
 * - `formatCost` — деньги журнала расходов, в долларах США. Хранилище держит шесть
 *   знаков (`MONEY_PLACES = 6` у сервера), поэтому вид выбирает, сколько из них показать.
 *
 * Строка не по контракту (без копеек, с другим разделителем, с буквами) показывается
 * как есть: выдумывать сумму за сервер фронт не должен.
 *
 * Список месяцев свой, без ICU: «19 ноя 2026» — тот же вид, что у дат задач и отделов.
 */

const MONTHS = [
  'янв',
  'фев',
  'мар',
  'апр',
  'мая',
  'июн',
  'июл',
  'авг',
  'сен',
  'окт',
  'ноя',
  'дек',
];

/** Пробел между разрядами: `1234567` → `1 234 567`. */
function groupDigits(whole: string): string {
  return whole.replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}

/**
 * Деньги задачи в рублях с копейками: `"1250.00"` → `1 250,00 ₽`, `"0.00"` → `0,00 ₽`.
 *
 * Ровно два знака после запятой, как в ответе сервера: сумма задачи приходит с двумя
 * знаками, и дополнять их нулём не приходится. Журнал расходов этот вид не использует —
 * у него своя валюта и своя разрядность (`formatCost`).
 */
export function formatMoney(value: string): string {
  const text = value.trim();
  const match = /^(\d+)(?:[.,](\d{1,2}))?$/.exec(text);
  if (match === null) {
    return text;
  }
  const [, whole = '', fraction] = match;
  const cents = (fraction ?? '').padEnd(2, '0');
  return `${groupDigits(whole)},${cents} ₽`;
}

/**
 * Сколько знаков после запятой показать у суммы журнала.
 *
 * Сервер считает деньги до шести знаков, но печатать все шесть всегда незачем: `119,227920`
 * человек читает хуже, чем `119,23`. Правило: копейки (два знака), а если сумма не ноль, но
 * в копейках её не видно — четыре знака, и только совсем мелкая сумма (`0,000001`) идёт с
 * шестью. Так запись на тысячные доли доллара не превращается на экране в `0,00 $`.
 */
function costPlaces(value: number): number {
  if (value === 0 || Math.round(value * 100) !== 0) {
    return 2;
  }
  if (Math.round(value * 10000) !== 0) {
    return 4;
  }
  return 6;
}

/**
 * Деньги журнала расходов в долларах США: `"119.227920"` → `119,23 $`, `"0.000400"` → `0,0004 $`.
 *
 * Округление здесь — вид, а не пересчёт: сумма уже посчитана сервером и хранится с шестью
 * знаками. Дальше второго знака оно уходит, только чтобы не потерять ненулевое значение
 * (`costPlaces`).
 */
export function formatCost(value: string): string {
  const text = value.trim();
  const match = /^(\d+)(?:[.,](\d+))?$/.exec(text);
  if (match === null) {
    return text;
  }
  const number = Number(text.replace(',', '.'));
  if (!Number.isFinite(number)) {
    return text;
  }
  const [whole = '0', fraction = '00'] = number.toFixed(costPlaces(number)).split('.');
  return `${groupDigits(whole)},${fraction} $`;
}

/**
 * Цена за 1 млн токенов: `"0.270000"` → `0,27`, `"1.100000"` → `1,10`, `"0.340000"` → `0,34`.
 *
 * Сервер отдаёт шесть знаков; хвостовые нули за вторым знаком в поле и в строке цен
 * не печатаются, иначе человек видел бы `0,270000` и отправлял это обратно. Валюта в
 * строке не печатается — её называет подпись единицы рядом («$ за 1 млн»).
 */
export function formatPrice(value: string): string {
  const text = value.trim();
  const match = /^(\d+)(?:[.,](\d+))?$/.exec(text);
  if (match === null) {
    return text;
  }
  const [, whole = '', fraction] = match;
  const digits = fraction ?? '';
  // Два знака остаются всегда (деньги), дальше — только значащие нули.
  const kept = digits.length <= 2 ? digits.padEnd(2, '0') : digits.replace(/0+$/, '').padEnd(2, '0');
  return `${whole},${kept}`;
}

/** Количество токенов: `1500000` → `1 500 000`. Число целое, его считает сервер. */
export function formatTokens(value: number): string {
  return groupDigits(String(value));
}

/**
 * Дата записи журнала в виде «19 ноя 2026».
 *
 * `spent_on` приходит календарной датой `ГГГГ-ММ-ДД` без времени: разбирается строка,
 * а не `new Date()`, иначе часовой пояс сдвинул бы день на сутки. Не по формату —
 * значение показывается как есть.
 */
export function formatSpentOn(value: string): string {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value.trim());
  if (match === null) {
    return value;
  }
  const [, year = '', month = '', day = ''] = match;
  const name = MONTHS[Number(month) - 1];
  if (name === undefined) {
    return value;
  }
  return `${Number(day)} ${name} ${year}`;
}
