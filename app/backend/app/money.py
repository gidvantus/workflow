"""Формат денег в ответах API: одна функция на все суммы проекта.

Деньги лежат в базе как `Numeric`, наружу уходят строкой ровно с двумя знаками:
фронт переставляет строку в вид `0,41 ₽` и сам не округляет. Копий этого формата быть
не должно: суммы строк журнала и итог проекта показываются на одном экране, и правка
вида денег (разряды, запятая) обязана касаться их одновременно.
"""

from decimal import Decimal


def format_money(value: object) -> str:
    """`Decimal("0.4")` из базы → `"0.40"`: деньги наружу уходят строкой с копейками.

    Принимается любое значение, из которого получается `Decimal`: из базы приходит
    `Decimal`, но валидатор схемы видит поле до проверки типа, поэтому не строкой и не
    числом его заранее не описать.
    """
    return f"{Decimal(str(value)):.2f}"
