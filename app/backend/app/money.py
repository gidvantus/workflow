"""Один расчёт денег журнала: формат, формула и единица прайса.

Расход проекта складывается из двух половин — смен, которые пишет отдел, и ручных
записей, которые вводит человек. Сумму обеих половин считает сервер, и считает её
**одной** функцией: две реализации «токены × цена / 1 000 000» разошлись бы на
округлении, и итог журнала перестал бы сходиться с суммой его строк.

Прайс один — четыре цены проекта (`projects.price_*`), и он в долларах США за
1 000 000 токенов. Второго прайса (тарифов расчёта в конфиге отдела) больше нет: смена
ценится по ценам проекта, поэтому сумма смены и сумма ручной записи — одни и те же
деньги.

Два формата, и оба нужны:

- `format_cost` — шесть знаков (`"0.420000"`). Так уходят наружу строки журнала:
  сессия в сотню токенов стоит доли цента, и округлять её до копейки значило бы терять
  расход мелкой сессии;
- `format_money` — два знака (`"0.40"`). Так уходит наружу `tasks.cost`: у задачи своя
  цена в рублях, и её вид этой правкой не меняется.
"""

from collections.abc import Mapping
from decimal import ROUND_HALF_UP, Decimal

# Знаков после точки у денег журнала: шесть, а не два — тариф за миллион токенов даёт
# доли цента, и это разные деньги, а не «ноль».
MONEY_PLACES = 6
MONEY_QUANTUM = Decimal("0.000001")

# Прайс проекта задан за 1 000 000 токенов — на него и делится произведение.
MILLION_TOKENS = Decimal(1_000_000)

# Четыре вида токенов и их цены: порядок один и тот же в запросе, модели и ответе.
# Ключи — имена колонок, а не имена полей контракта (`in`, `out`, `cacheRead`,
# `cacheWrite`): переименование ключа контракта не должно менять формулу.
TOKEN_PRICE_FIELDS: tuple[tuple[str, str], ...] = (
    ("tokens_input", "price_input"),
    ("tokens_output", "price_output"),
    ("tokens_cache_read", "price_cache_read"),
    ("tokens_cache_write", "price_cache_write"),
)


def format_cost(value: object) -> str:
    """Деньги журнала строкой: `Decimal("0.42")` → `"0.420000"`.

    Приведение к `Decimal` идёт через `str`, а не через `float`: `float` уже потерял
    точность до вызова, и `Decimal(0.1)` вернул бы `0.1000000000000000055...`.
    """
    return f"{Decimal(str(value)):.{MONEY_PLACES}f}"


def format_money(value: object) -> str:
    """Деньги задачи строкой с копейками: `Decimal("0.4")` → `"0.40"`.

    Принимается любое значение, из которого получается `Decimal`: из базы приходит
    `Decimal`, но валидатор схемы видит поле до проверки типа, поэтому не строкой и не
    числом его заранее не описать.
    """
    return f"{Decimal(str(value)):.2f}"


def amount_for(tokens: Mapping[str, int], prices: Mapping[str, object]) -> Decimal:
    """Сумма расхода: Σ количество × цена / 1 000 000, `ROUND_HALF_UP` до шести знаков.

    `tokens` — количества по ключам `TOKEN_PRICE_FIELDS` (имена колонок), `prices` —
    цены проекта по парным ключам. Отсутствие ключа — ошибка вызывающего, а не ноль:
    количество и цену обязана дать проверка тела, а не эта функция.

    Округление одно на сумму, а не на каждое слагаемое: иначе четыре сложения дали бы
    другой последний знак, чем одно умножение, и сумма строк не сошлась бы с итогом.
    """
    total = Decimal(0)
    for token_field, price_field in TOKEN_PRICE_FIELDS:
        total += Decimal(tokens[token_field]) * Decimal(str(prices[price_field]))
    return (total / MILLION_TOKENS).quantize(MONEY_QUANTUM, rounding=ROUND_HALF_UP)
